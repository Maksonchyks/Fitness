        private static MealPlanTemplate CreateTemplate(
            string name, string description,
            (string dishName, string desc, float cal, float prot, float fat, float carbs) breakfast,
            (string dishName, string desc, float cal, float prot, float fat, float carbs) lunch,
            (string dishName, string desc, float cal, float prot, float fat, float carbs) dinner)
        {
            var meals = new List<TemplateMeal>
            {
                new TemplateMeal(MealType.Breakfast, breakfast.dishName, breakfast.desc,
                    new NutritionValue(breakfast.cal, breakfast.prot, breakfast.fat, breakfast.carbs)),
                new TemplateMeal(MealType.Lunch, lunch.dishName, lunch.desc,
                    new NutritionValue(lunch.cal, lunch.prot, lunch.fat, lunch.carbs)),
                new TemplateMeal(MealType.Dinner, dinner.dishName, dinner.desc,
                    new NutritionValue(dinner.cal, dinner.prot, dinner.fat, dinner.carbs))
            };

            return MealPlanTemplate.Create(name, description, meals);
        }
